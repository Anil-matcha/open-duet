const catalogs: Record<Locale, Partial<Record<MessageKey, string>>> = {
  en,
  de,
  es,
  fr,
  it,
  ja,
  ko,
  nl,
  pl,
  pt,
  ru,
  tr,
  zh,
};

function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

type StorageLike = Pick<Storage, "getItem" | "setItem" | "removeItem">;

export function parseLanguageChoice(value: unknown): LanguageChoice {
  // Older versions stored "system". Keep those browsers on the documented English default.
  return typeof value === "string" && isLocale(value) ? value : "en";
}

export function resolveLocale(choice: LanguageChoice, _systemLocale = "en"): Locale {
  return choice;
}

export function readLanguage(storage: () => StorageLike): LanguageChoice {
  try {
    return parseLanguageChoice(storage().getItem(LANGUAGE_KEY));
  } catch {
    return "en";
  }
}

export function writeLanguage(storage: () => StorageLike, choice: LanguageChoice): boolean {
  try {
    storage().setItem(LANGUAGE_KEY, choice);
    return true;
  } catch {
    return false;
  }
}

type DocumentLike = {
  documentElement: {
    lang: string;
    dataset: Record<string, string | undefined>;
  };
};

export function applyLanguage(doc: DocumentLike, choice: LanguageChoice, _systemLocale = "en"): Locale {
  doc.documentElement.lang = LANGUAGE_TAGS[choice];
  doc.documentElement.dataset.languageChoice = choice;
  return choice;
}

export const LANGUAGE_INIT_SCRIPT =
  '(function(){var d=document.documentElement,c="en",a=' +
  JSON.stringify(LOCALES) +
  ';function ok(v){return a.indexOf(v)>=0}' +
  'try{var v=localStorage.getItem(' + JSON.stringify(LANGUAGE_KEY) + ');if(ok(v))c=v}catch(e){}' +
  'd.dataset.languageChoice=c;d.lang=c==="pt"?"pt-BR":c==="zh"?"zh-CN":c})();';

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const template: string = catalogs[locale][key as MessageKey] ?? en[key as EnglishKey] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

// English is retained for older call sites and source-oriented tests.
export function t(key: MessageKey | string, params?: Record<string, string | number>): string {
  return translate("en", key, params);
}
